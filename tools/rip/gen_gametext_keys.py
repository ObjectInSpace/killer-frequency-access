"""Generate Generated\\GameTextKeys.cs: the GameText string table's key id -> key name.
A DiegeticTextLocalizer's LocalizedString usually refers to its entry by id; this table turns
that id into the entry's name (e.g. "AlibiAsset.ClassOf68"), which ImageDescriptions is keyed on.
Usage: python -I gen_gametext_keys.py <StreamingAssets/aa/StandaloneWindows64> <out.cs>
Reads localization-assets-shared_*.bundle with UnityPy.
"""
import UnityPy, sys, glob, os

aa, out = sys.argv[1:3]
shared = glob.glob(os.path.join(aa, 'localization-assets-shared_*.bundle'))[0]
table = None
for obj in UnityPy.load(shared).objects:
    if obj.type.name != 'MonoBehaviour':
        continue
    try:
        t = obj.read_typetree()
    except Exception:
        continue
    if t.get('m_TableCollectionName') == 'GameText' and 'm_Entries' in t:
        table = t
        break

entries = sorted(table['m_Entries'], key=lambda e: e['m_Key'])
lines = [
    '// <auto-generated>',
    '// Generated by tools\\rip\\gen_gametext_keys.py from the game\'s localization-assets-shared bundle.',
    '// Do not edit by hand; fix the generator and rerun it.',
    '// </auto-generated>',
    'using System.Collections.Generic;',
    '',
    'namespace Killer_Frequency_Access;',
    '',
    'internal static class GameTextKeys',
    '{',
    '    /// <summary>The GameText table\'s collection name GUID, as a TableReference stores it.</summary>',
    f'    internal const string TableGuid = "{table["m_TableCollectionNameGuidString"]}";',
    '',
    '    /// <summary>GameText entry name per key id.</summary>',
    '    internal static readonly Dictionary<long, string> NameById = new()',
    '    {',
]
def cs(s):
    return s.replace('\\', '\\\\').replace('"', '\\"').replace('\r', '\\r').replace('\n', '\\n')

for e in entries:
    lines.append(f'        [{e["m_Id"]}] = "{cs(e["m_Key"])}",')
lines += ['    };', '}', '']
open(out, 'w', encoding='utf-8', newline='\r\n').write('\n'.join(lines))
print(len(entries), 'GameText keys')
